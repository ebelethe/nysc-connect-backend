CREATE TABLE posts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  communityId INT NOT NULL,
  corpsMemberId INT NOT NULL,
  title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
  location VARCHAR(255) NULL,
  likeCount INT DEFAULT 0,
  createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (communityId) REFERENCES communities(id),
  FOREIGN KEY (corpsMemberId) REFERENCES corps_members(id)
);

CREATE TABLE post_images (
  id INT AUTO_INCREMENT PRIMARY KEY,
  postId INT NOT NULL,
  imageUrl VARCHAR(500) NOT NULL,
  createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (postId) REFERENCES posts(id) ON DELETE CASCADE
);

CREATE TABLE post_tags (
  id INT AUTO_INCREMENT PRIMARY KEY,
  postId INT NOT NULL,
  tagName VARCHAR(50) NOT NULL,
  FOREIGN KEY (postId) REFERENCES posts(id) ON DELETE CASCADE
);

CREATE TABLE post_likes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  postId INT NOT NULL,
  corpsMemberId INT NOT NULL,
  createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY unique_like (postId, corpsMemberId),
  FOREIGN KEY (postId) REFERENCES posts(id) ON DELETE CASCADE,
  FOREIGN KEY (corpsMemberId) REFERENCES corps_members(id)
);

CREATE TABLE post_comments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  postId INT NOT NULL,
  corpsMemberId INT NOT NULL,
  content TEXT NOT NULL,
  createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (postId) REFERENCES posts(id) ON DELETE CASCADE,
  FOREIGN KEY (corpsMemberId) REFERENCES corps_members(id)
);

CREATE TABLE polls (
  id INT AUTO_INCREMENT PRIMARY KEY,
  postId INT NOT NULL,
  question VARCHAR(500) NOT NULL,
  durationDays INT NOT NULL,
  expiresAt DATETIME NOT NULL,
  createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (postId) REFERENCES posts(id) ON DELETE CASCADE
);

CREATE TABLE poll_options (
  id INT AUTO_INCREMENT PRIMARY KEY,
  pollId INT NOT NULL,
  optionText VARCHAR(255) NOT NULL,
  FOREIGN KEY (pollId) REFERENCES polls(id) ON DELETE CASCADE
);

CREATE TABLE poll_votes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  pollId INT NOT NULL,
  optionId INT NOT NULL,
  corpsMemberId INT NOT NULL,
  createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY unique_vote (pollId, corpsMemberId),
  FOREIGN KEY (pollId) REFERENCES polls(id) ON DELETE CASCADE,
  FOREIGN KEY (optionId) REFERENCES poll_options(id) ON DELETE CASCADE,
  FOREIGN KEY (corpsMemberId) REFERENCES corps_members(id)
);

CREATE TABLE saved_posts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  corpsMemberId INT NOT NULL,
  postId INT NOT NULL,
  createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY unique_save (corpsMemberId, postId),
  FOREIGN KEY (corpsMemberId) REFERENCES corps_members(id),
  FOREIGN KEY (postId) REFERENCES posts(id) ON DELETE CASCADE
);

